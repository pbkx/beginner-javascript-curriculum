// You can combine numbers and math operators
// JavaScript follows the order of operations
console.log(2 + 3 * 4);  // prints 14 (3 * 4 = 12, then 2 + 12)
console.log((2 + 3) * 4);  // prints 20 (2 + 3 = 5, then 5 * 4)