console.log(6 + 4);  // Addition: adds two numbers

console.log(10 - 3);  // Subtraction: subtracts the second number from the first number

console.log(9 * 5);  // Multiplication: multiplies two numbers

console.log(15 / 2);  // Division: divides and gives a decimal result

console.log(Math.floor(7.8));  // Floor: rounds down to a whole number

console.log(9 % 2);  // Modulus: gives the remainder

console.log(2 ** 3);  // Exponentiation: first number raised to the power of second number

